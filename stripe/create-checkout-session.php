<?php
/**
 * Stripe Checkout Session Creation
 * Creates a Stripe checkout session for invoice payment
 */

// Suppress all output and errors to prevent HTML in JSON response
// CRITICAL: Disable Xdebug BEFORE any other operations
if (function_exists('xdebug_disable')) {
    xdebug_disable();
}
if (function_exists('ini_set')) {
    @ini_set('xdebug.overload_var_dump', 0);
    @ini_set('xdebug.default_enable', 0);
    @ini_set('xdebug.show_exception_trace', 0);
    @ini_set('xdebug.mode', 'off'); // PHP 8.x way to disable Xdebug
}

error_reporting(E_ALL);
ini_set('display_errors', 0);
ini_set('log_errors', 1);
ini_set('html_errors', 0);
ini_set('xdebug.force_display_errors', 0);
ini_set('xdebug.force_error_reporting', 0);

// Start output buffering immediately to catch any warnings/errors
ob_start();

// Set headers first
header('Content-Type: application/json');
header('Access-Control-Allow-Origin: *');
header('Access-Control-Allow-Methods: POST, OPTIONS');
header('Access-Control-Allow-Headers: Content-Type');

if ($_SERVER['REQUEST_METHOD'] === 'OPTIONS') {
    ob_clean();
    http_response_code(200);
    exit();
}

// Health check: GET request returns version so you can verify this script runs on production
if ($_SERVER['REQUEST_METHOD'] === 'GET') {
    ob_clean();
    header('Content-Type: application/json');
    http_response_code(200);
    echo json_encode([
        'ok' => true,
        'script' => 'create-checkout-session',
        'version' => '2.1',
        'message' => 'Use POST with billing_period_id, amount, currency to create a session. Check server PHP error_log for 500 debugging.',
    ]);
    ob_end_flush();
    exit();
}

// Helper function to send JSON error response
function sendJsonError($message, $code = 400, $details = null) {
    ob_clean();
    http_response_code($code);
    $response = [
        'success' => false,
        'error' => $message
    ];
    if ($details !== null) {
        $response['details'] = $details;
    }
    echo json_encode($response);
    ob_end_flush();
    exit();
}

// Helper function to send JSON success response
function sendJsonSuccess($data) {
    ob_clean();
    http_response_code(200);
    echo json_encode(array_merge(['success' => true], $data));
    ob_end_flush();
    exit();
}

try {
    // Suppress any output from included files
    $oldErrorReporting = error_reporting(E_ALL & ~E_WARNING & ~E_NOTICE);
    
    // Get the correct paths
    $connPath = __DIR__ . '/../conn.php';
    $configPath = __DIR__ . '/config.php';
    
    // Normalize paths for Windows
    $connPath = str_replace('\\', '/', $connPath);
    $configPath = str_replace('\\', '/', $configPath);
    
    // Use realpath to resolve any symlinks/aliases
    $connPathReal = realpath($connPath) ?: $connPath;
    $configPathReal = realpath($configPath) ?: $configPath;
    
    // Log paths for debugging if needed
    if (!file_exists($connPathReal)) {
        error_log("conn.php not found at: " . $connPathReal . " (original: " . $connPath . ")");
        error_log("__DIR__ is: " . __DIR__);
        sendJsonError('Database configuration file not found', 500);
    }
    
    if (!file_exists($configPathReal)) {
        error_log("config.php not found at: " . $configPathReal . " (original: " . $configPath . ")");
        sendJsonError('Stripe configuration file not found', 500);
    }
    
    // Include files with output suppression
    @require_once $connPathReal;
    @require_once $configPathReal;
    
    error_reporting($oldErrorReporting);
    
    // Check if any output was generated by included files
    $output = ob_get_contents();
    if (!empty($output) && trim($output) !== '') {
        ob_clean();
        error_log("Unexpected output before processing in create-checkout-session.php: " . substr($output, 0, 500));
        sendJsonError('Server configuration error. Please check server logs.', 500);
    }

    // Ensure Stripe config constants exist (prevents generic 500 from undefined constant on production)
    if (!defined('SUPPORTED_CURRENCIES') || !is_array(SUPPORTED_CURRENCIES)) {
        error_log("[CREATE-CHECKOUT-SESSION] SUPPORTED_CURRENCIES missing or invalid in config");
        sendJsonError('Stripe configuration incomplete (SUPPORTED_CURRENCIES). Check server logs.', 500);
    }
    if (!defined('PAYMENT_METHOD_TYPES') || !is_array(PAYMENT_METHOD_TYPES)) {
        error_log("[CREATE-CHECKOUT-SESSION] PAYMENT_METHOD_TYPES missing or invalid in config");
        sendJsonError('Stripe configuration incomplete (PAYMENT_METHOD_TYPES). Check server logs.', 500);
    }

    if (!$conn) {
        $errorMsg = isset($conn_error) ? $conn_error : 'Unknown database error';
        error_log("Database connection failed: " . $errorMsg);
        sendJsonError('Database connection failed', 500);
    }

    // Get payment data from request
    $input = @file_get_contents('php://input');
    if ($input === false || empty($input)) {
        sendJsonError('No request data received');
    }
    
    $data = json_decode($input, true);
    if (json_last_error() !== JSON_ERROR_NONE) {
        sendJsonError('Invalid JSON data: ' . json_last_error_msg());
    }
    
    if (!is_array($data)) {
        sendJsonError('Request data must be a JSON object');
    }
    
    // Validate required fields
    $errors = [];
    
    // CRITICAL: billing_period_id is REQUIRED - no fallbacks to prevent multi-row issues
    $billingPeriodId = isset($data['billing_period_id']) && !empty($data['billing_period_id'])
        ? filter_var($data['billing_period_id'], FILTER_VALIDATE_INT)
        : null;
    
    error_log("create-checkout-session received: billing_period_id=" . ($billingPeriodId ?? 'null'));
    
    if (!$billingPeriodId || $billingPeriodId <= 0) {
        error_log("ERROR: billing_period_id is missing or invalid. Received: " . (isset($data['billing_period_id']) ? var_export($data['billing_period_id'], true) : 'not set'));
        sendJsonError('billing_period_id is required. The billing period ID is missing from the request. Please refresh the page and try again.', 400);
    }
    
    error_log("Using billing_period_id: $billingPeriodId");
    
    if (!isset($data['amount']) || !is_numeric($data['amount']) || $data['amount'] <= 0) {
        $errors[] = 'Valid amount is required (must be a positive number)';
    }
    
    if (!isset($data['currency']) || empty($data['currency'])) {
        $errors[] = 'currency is required';
    }
    
    if (!empty($errors)) {
        sendJsonError('Validation failed', 400, $errors);
    }
    
    // billing_period_id is provided - no need to validate account_id or month_year
    // They will be retrieved from the database using billing_period_id
    
    // Validate amount and currency (still required)
    $amount = filter_var($data['amount'], FILTER_VALIDATE_FLOAT);
    if ($amount === false || $amount <= 0) {
        sendJsonError('Invalid amount: must be a positive number');
    }
    
    $currency = strtolower(trim($data['currency']));
    if (!in_array($currency, SUPPORTED_CURRENCIES)) {
        sendJsonError('Currency not supported. Supported currencies: ' . implode(', ', SUPPORTED_CURRENCIES));
    }
    $currency = mysqli_real_escape_string($conn, $currency);
    
    // Verify billing period exists and is unpaid - use billing_period_id directly
    $billingPeriodIdEscaped = (int)$billingPeriodId;

    // Determine broker (capital.com, binance, ig) — REQUIRED, no silent fallback.
    // Without a broker we cannot know which invoice table to read/update, and a wrong
    // default has previously caused binance invoice IDs to look up billing_periods.
    if (!isset($data['broker']) || !in_array($data['broker'], ['capital.com', 'binance', 'ig'], true)) {
        sendJsonError('broker is required and must be one of: capital.com, binance, ig', 400);
    }
    $broker = $data['broker'];

    // Build broker-aware query
    if ($broker === 'binance') {
        $checkQuery = "SELECT bp.id, NULL AS account_id, bp.user_id, bp.month_year, bp.total_fee,
                        bp.realized_pnl, bp.unrealized_pnl, bp.fee_realized, bp.fee_unrealized, bp.status,
                        a.name AS account_name, '' AS account_email
                       FROM binance_invoices bp
                       INNER JOIN binance_accounts a ON bp.api_key = a.api_key
                       WHERE bp.id = $billingPeriodIdEscaped LIMIT 1";
    } elseif ($broker === 'ig') {
        $checkQuery = "SELECT bp.id, bp.account_id, bp.user_id, bp.month_year, bp.total_fee,
                        bp.realized_pnl, bp.unrealized_pnl, bp.fee_realized, bp.fee_unrealized, bp.status,
                        a.name AS account_name, a.email AS account_email
                       FROM ig_invoices bp
                       INNER JOIN ig_accounts a ON bp.api_key = a.api_key
                       WHERE bp.id = $billingPeriodIdEscaped LIMIT 1";
    } else {
        $checkQuery = "SELECT bp.id, bp.account_id, bp.user_id, bp.month_year, bp.total_fee,
                        bp.realized_pnl, bp.unrealized_pnl, bp.fee_realized, bp.fee_unrealized, bp.status,
                        a.name AS account_name, a.email AS account_email
                       FROM billing_periods bp
                       INNER JOIN accounts a ON bp.account_id = a.id
                       WHERE bp.id = $billingPeriodIdEscaped LIMIT 1";
    }

    error_log("Looking up billing period by ID: $billingPeriodId (broker: $broker)");

    $checkResult = @mysqli_query($conn, $checkQuery);
    if (!$checkResult) {
        $dbError = mysqli_error($conn);
        error_log("Database query error in create-checkout-session.php: " . $dbError);
        sendJsonError('Database error while verifying billing period', 500);
    }

    if (mysqli_num_rows($checkResult) === 0) {
        error_log("Billing period not found by ID: $billingPeriodId (broker: $broker)");

        sendJsonError('Billing period not found. The billing period with ID ' . $billingPeriodId . ' does not exist in the database. Please refresh the page and try again.', 404, [
            'billing_period_id' => $billingPeriodId
        ]);
    }

    $billingPeriod = mysqli_fetch_assoc($checkResult);
    if (!$billingPeriod) {
        sendJsonError('Failed to retrieve billing period data', 500);
    }

    // Get values from database result (not from request)
    $accountId = (int)($billingPeriod['account_id'] ?? 0);
    $userId = $billingPeriod['user_id'];
    $monthYear = $billingPeriod['month_year'];
    
    // Check if already paid
    if (isset($billingPeriod['status']) && $billingPeriod['status'] === 'paid') {
        sendJsonError('This billing period has already been paid', 400);
    }
    
    // Use the stored total_fee from billing_periods (calculated during invoice generation with HWM logic)
    // This is more reliable than recalculating, as it uses the exact values from generation time
    $expectedAmount = (float)($billingPeriod['total_fee'] ?? 0);
    
    // Verify amount matches at integer-cent precision (no floating point tolerance).
    $expectedCents = (int)round($expectedAmount * 100);
    $receivedCents = (int)round($amount * 100);
    if ($expectedCents !== $receivedCents) {
        sendJsonError('Amount mismatch', 400, [
            'expected' => $expectedAmount,
            'received' => $amount,
            'expected_cents' => $expectedCents,
            'received_cents' => $receivedCents,
            'stored_total_fee' => $billingPeriod['total_fee'],
            'note' => 'Expected amount is from invoice total_fee (calculated with HWM logic during invoice generation)'
        ]);
    }
    
    // Load Stripe PHP library
    // Use simple relative path: stripe/../vendor/autoload.php = vendor/autoload.php
    $stripeAutoloadPath = __DIR__ . '/../vendor/autoload.php';
    
    // Normalize path to forward slashes (works on Windows)
    $stripeAutoloadPath = str_replace('\\', '/', $stripeAutoloadPath);
    
    // Check if file exists
    if (!file_exists($stripeAutoloadPath)) {
        error_log("Stripe library not found at: " . $stripeAutoloadPath);
        error_log("__DIR__ = " . __DIR__);
        error_log("Expected path: " . dirname(__DIR__) . "/vendor/autoload.php");
        sendJsonError('Stripe PHP library not found. Please ensure vendor/autoload.php exists.', 500);
    }
    
    // Suppress ALL output during require - critical to prevent Xdebug HTML
    $oldErrorReporting = error_reporting(0);
    $oldDisplayErrors = ini_get('display_errors');
    $oldHtmlErrors = ini_get('html_errors');
    ini_set('display_errors', 0);
    ini_set('html_errors', 0);
    
    // Clear any existing output buffer content
    if (ob_get_level() > 0) {
        ob_clean();
    }
    
    // Use nested output buffering to catch ANY output (including Xdebug HTML)
    $nestedObLevel = ob_get_level();
    ob_start();
    
    try {
        // Try to require the autoload file
        // Using require_once instead of include to ensure it loads
        $loaded = @require_once $stripeAutoloadPath;
    } catch (Throwable $e) {
        // Catch any exceptions during require
        ob_end_clean();
        error_reporting($oldErrorReporting);
        ini_set('display_errors', $oldDisplayErrors);
        ini_set('html_errors', $oldHtmlErrors);
        error_log("Exception loading Stripe library: " . $e->getMessage());
        sendJsonError('Failed to load Stripe PHP library: ' . $e->getMessage(), 500);
    }
    
    // Get any output that was generated (Xdebug HTML, warnings, etc.)
    $requireOutput = ob_get_contents();
    ob_end_clean();
    
    // Restore settings
    error_reporting($oldErrorReporting);
    ini_set('display_errors', $oldDisplayErrors);
    ini_set('html_errors', $oldHtmlErrors);
    
    // If any output was generated (like Xdebug HTML), log it and fail
    if (!empty($requireOutput) && trim($requireOutput) !== '') {
        // Check if it's HTML (Xdebug output)
        if (stripos($requireOutput, '<') !== false || stripos($requireOutput, '<br') !== false) {
            error_log("Xdebug HTML output detected during Stripe library load. First 500 chars: " . substr($requireOutput, 0, 500));
            // Try to extract the actual error message if possible
            if (preg_match('/Warning: (.+?) in/', $requireOutput, $matches)) {
                $errorMsg = $matches[1];
                sendJsonError('Server configuration error: ' . htmlspecialchars($errorMsg, ENT_QUOTES, 'UTF-8'), 500);
            } else {
                sendJsonError('Server configuration error: Xdebug is outputting HTML. Please disable Xdebug or configure it to not output HTML errors.', 500);
            }
        } else {
            // Non-HTML output, but still unexpected
            error_log("Unexpected output during Stripe library load: " . substr($requireOutput, 0, 500));
            sendJsonError('Failed to load Stripe PHP library. Please check server configuration.', 500);
        }
    }
    
    // Check if the library was actually loaded
    if (!$loaded) {
        error_log("Failed to load Stripe autoload.php from: " . $stripeAutoloadPath);
        sendJsonError('Failed to load Stripe PHP library. The autoload file may be corrupted.', 500);
    }
    
    // Verify Stripe classes are available
    // Note: class_exists with false parameter doesn't trigger autoload, so we need to check without it
    // or explicitly try to use the class to trigger autoload
    if (!class_exists('\Stripe\Stripe')) {
        error_log("Stripe class not found after loading autoload.php");
        error_log("Autoload path used: " . $stripeAutoloadPath);
        error_log("Vendor directory exists: " . (is_dir(dirname($stripeAutoloadPath)) ? 'yes' : 'no'));
        sendJsonError('Stripe PHP library failed to initialize. Classes not found. Please ensure Stripe is installed via Composer.', 500);
    }
    
    // Initialize Stripe with secret key from config
    try {
        $stripeKey = getStripeSecretKey();
        if (empty($stripeKey)) {
            sendJsonError('Stripe secret key not configured', 500);
        }
        \Stripe\Stripe::setApiKey($stripeKey);
    } catch (Exception $e) {
        error_log("Error setting Stripe API key: " . $e->getMessage());
        sendJsonError('Failed to initialize Stripe', 500);
    }
    
    // Get success and cancel URLs
    $successUrl = getSuccessUrl();
    $cancelUrl = getCancelUrl();
    
    if (empty($successUrl) || empty($cancelUrl)) {
        error_log("Success or cancel URL is empty");
        sendJsonError('Payment URLs not configured', 500);
    }
    
    // Format month_year for display (e.g., "2025-11" -> "November 2025")
    // Note: month_year already represents the billing month (previous month) from generate_invoices.php
    // When invoice is generated on Dec 1st, month_year = "2025-11" (November, the billing month)
    // So we just format it directly without subtracting 1 month
    $formattedMonthYear = $monthYear;
    try {
        $date = DateTime::createFromFormat('Y-m', $monthYear);
        if ($date) {
            // month_year already is the billing month, just format it
            $formattedMonthYear = $date->format('F Y'); // "November 2025" for month_year "2025-11"
        }
    } catch (Exception $e) {
        // If parsing fails, use the original value
        error_log("Failed to format month_year: " . $monthYear . " - " . $e->getMessage());
    }
    
    // MAIN FIX: Checkout ALWAYS uses a Stripe Customer (never customer_email).
    // Without a Customer, Stripe uses the card in a one-off PaymentIntent and marks the PM single-use.
    // Then auto-charge fails with "previously used without Customer attachment".
    // We require $stripeCustomerId before creating the session; no fallback to customer_email.
    $stripeCustomerId = null;
    $userIdEscaped = mysqli_real_escape_string($conn, $userId);
    
    // Check if customer already exists in our database
    $existingCustomerQuery = "SELECT stripe_customer_id FROM stripe_payment_methods WHERE uni_id = '$userIdEscaped' AND is_active = 1 LIMIT 1";
    $existingCustomerResult = mysqli_query($conn, $existingCustomerQuery);
    
    if ($existingCustomerResult && mysqli_num_rows($existingCustomerResult) > 0) {
        $existingRow = mysqli_fetch_assoc($existingCustomerResult);
        $stripeCustomerId = $existingRow['stripe_customer_id'] ?? null;
        mysqli_free_result($existingCustomerResult);
        
        // Verify customer still exists in Stripe
        if ($stripeCustomerId) {
            try {
                \Stripe\Customer::retrieve($stripeCustomerId);
                error_log("Using existing Stripe customer: $stripeCustomerId");
            } catch (\Stripe\Exception\InvalidRequestException $e) {
                // Customer doesn't exist in Stripe, create new one
                $stripeCustomerId = null;
                error_log("Existing customer ID invalid, will create new one: " . $e->getMessage());
            }
        }
    }
    
    // Create new customer if we don't have one
    if (!$stripeCustomerId) {
        $customerParams = [
            'metadata' => [
                'uni_id' => $userId
            ]
        ];
        
        // Get user email
        $userEmail = $billingPeriod['account_email'] ?? null;
        if (!$userEmail) {
            // Try to get from user_credentials
            $userEmailQuery = "SELECT email FROM user_credentials WHERE uni_id = '$userIdEscaped' LIMIT 1";
            $userEmailResult = mysqli_query($conn, $userEmailQuery);
            if ($userEmailResult && mysqli_num_rows($userEmailResult) > 0) {
                $userEmailRow = mysqli_fetch_assoc($userEmailResult);
                $userEmail = $userEmailRow['email'] ?? null;
                mysqli_free_result($userEmailResult);
            }
        }
        
        if ($userEmail) {
            $customerParams['email'] = $userEmail;
        }
        
        try {
            $stripeCustomer = \Stripe\Customer::create($customerParams);
            $stripeCustomerId = $stripeCustomer->id;
            error_log("Created new Stripe customer: $stripeCustomerId for user: $userId");
        } catch (Exception $e) {
            error_log("Failed to create Stripe customer: " . $e->getMessage());
            sendJsonError('Unable to set up payment for future invoices. Please try again or contact support.', 500);
        }
    }
    
    // Require Customer for checkout so PaymentMethod is reusable for auto-charge
    if (empty($stripeCustomerId)) {
        error_log("Checkout aborted: no Stripe Customer (required for reusable payment method)");
        sendJsonError('Unable to set up payment for future invoices. Please try again or contact support.', 500);
    }
    
    // Prepare session data
    $sessionData = [
        'payment_method_types' => PAYMENT_METHOD_TYPES,
        'line_items' => [[
            'price_data' => [
                'currency' => $currency,
                'product_data' => [
                    'name' => 'Invoice Payment - ' . htmlspecialchars($billingPeriod['account_name'], ENT_QUOTES, 'UTF-8'),
                    'description' => 'Billing Period: ' . $formattedMonthYear,
                ],
                'unit_amount' => (int)round($amount * 100), // Convert to cents, round to avoid floating point issues
            ],
            'quantity' => 1,
        ]],
        'mode' => 'payment',
        'success_url' => $successUrl,
        'cancel_url' => $cancelUrl,
        'metadata' => [
            'account_id' => (string)$accountId,
            'user_id' => $userId,
            'month_year' => $monthYear,
            'billing_period_id' => (string)$billingPeriod['id'],
            'broker' => $broker,
        ],
    ];
    
    // Use Customer so PaymentMethod is attached and reusable for auto-charge (no customer_email fallback)
    $sessionData['customer'] = $stripeCustomerId;
    unset($sessionData['customer_email']); // Ensure we never send customer_email; PM must be attached to Customer
    // Tell Stripe to attach the PaymentMethod to the customer for future off-session charges (auto-charge)
    $sessionData['payment_intent_data'] = [
        'setup_future_usage' => 'off_session',
    ];
    error_log("Checkout session will use customer: $stripeCustomerId (setup_future_usage=off_session for auto-charge)");
    
    // Create checkout session
    try {
        $session = \Stripe\Checkout\Session::create($sessionData);
        
        if (!$session || !isset($session->id) || !isset($session->url)) {
            error_log("Stripe session created but missing id or url");
            sendJsonError('Failed to create checkout session: invalid response from Stripe', 500);
        }
        
        sendJsonSuccess([
            'sessionId' => $session->id,
            'sessionUrl' => $session->url,
        ]);
        
    } catch (\Stripe\Exception\CardException $e) {
        error_log("Stripe CardException: " . $e->getMessage());
        sendJsonError('Card error: ' . $e->getMessage(), 400);
    } catch (\Stripe\Exception\RateLimitException $e) {
        error_log("Stripe RateLimitException: " . $e->getMessage());
        sendJsonError('Rate limit error. Please try again later.', 429);
    } catch (\Stripe\Exception\InvalidRequestException $e) {
        error_log("Stripe InvalidRequestException: " . $e->getMessage());
        sendJsonError('Invalid request to Stripe: ' . $e->getMessage(), 400);
    } catch (\Stripe\Exception\AuthenticationException $e) {
        error_log("Stripe AuthenticationException: " . $e->getMessage());
        sendJsonError('Stripe authentication failed. Please check API keys.', 500);
    } catch (\Stripe\Exception\ApiConnectionException $e) {
        error_log("Stripe ApiConnectionException: " . $e->getMessage());
        sendJsonError('Network error connecting to Stripe. Please try again.', 503);
    } catch (\Stripe\Exception\ApiErrorException $e) {
        error_log("Stripe ApiErrorException: " . $e->getMessage());
        sendJsonError('Stripe API error: ' . $e->getMessage(), 400);
    } catch (Exception $e) {
        error_log("Unexpected error in create-checkout-session.php: " . $e->getMessage() . " | Trace: " . $e->getTraceAsString());
        sendJsonError('An unexpected error occurred: ' . $e->getMessage(), 500);
    } catch (Error $e) {
        error_log("[CREATE-CHECKOUT-SESSION] PHP Error: " . $e->getMessage() . " | File: " . $e->getFile() . ":" . $e->getLine() . " | Trace: " . $e->getTraceAsString());
        sendJsonError('A system error occurred', 500);
    }

} catch (Exception $e) {
    error_log("[CREATE-CHECKOUT-SESSION] Top-level Exception: " . $e->getMessage() . " | Trace: " . $e->getTraceAsString());
    sendJsonError('An error occurred: ' . $e->getMessage(), 500);
} catch (Error $e) {
    error_log("[CREATE-CHECKOUT-SESSION] Top-level PHP Error: " . $e->getMessage() . " | File: " . $e->getFile() . ":" . $e->getLine() . " | Trace: " . $e->getTraceAsString());
    sendJsonError('A system error occurred', 500);
} catch (Throwable $e) {
    error_log("[CREATE-CHECKOUT-SESSION] Top-level Throwable: " . $e->getMessage() . " | File: " . $e->getFile() . ":" . $e->getLine() . " | Trace: " . $e->getTraceAsString());
    sendJsonError('A system error occurred', 500);
}

// Final safety net - if we reach here, something went very wrong
// Ensure we always return valid JSON
if (ob_get_level() > 0) {
    $remainingOutput = ob_get_contents();
    if (!empty($remainingOutput)) {
        ob_clean();
        error_log("Unexpected output at end of create-checkout-session.php: " . substr($remainingOutput, 0, 500));
    }
    ob_end_clean();
}

// If we somehow reach here without exiting, send a generic error
header('Content-Type: application/json');
http_response_code(500);
echo json_encode(['success' => false, 'error' => 'An unexpected error occurred']);
exit();

